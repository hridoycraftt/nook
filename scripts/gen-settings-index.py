#!/usr/bin/env python3
"""Builds Sources/Uthon/App/SettingsIndex.swift: every label shown in Settings, with the page
it is on, so the Settings search can find any setting. Run after changing Settings pages
(the build script runs it too)."""
import re, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ["Sources/Uthon/App/SettingsWindow.swift", "Sources/Uthon/App/FeatureSettings.swift",
         "Sources/Uthon/App/WallpaperSettings.swift"]
TABS = {
    "GeneralSettings": "general", "LookSettings": "look", "HomeSettings": "home", "HomeItemRow": "home",
    "IslandSettings": "island", "WidgetDataSettings": "widgets", "BatteriesSection": "widgets",
    "WorldClockSearch": "widgets", "AlertsSettings": "alerts", "PopupDurationSettings": "alerts",
    "ProfilesSettings": "profiles", "ProfileRow": "profiles", "DockSettings": "dock", "CareSettings": "care",
    "VerseSettings": "verse", "NetworkSettings": "network", "NotificationSettings": "notifications",
    "NightSettings": "night", "BottomDockSettings": "bottomDock", "AISettings": "ai", "RamadanSettings": "ramadan",
    "WallpaperSettings": "wallpaper", "StyleCard": "wallpaper", "DesktopPictureSection": "wallpaper",
}
SKIP = {"Off", "On", "None", "Add", "Remove", "Reset", "Show", "Play", "Stop", "Choose…", "Done", "Edit", "Cancel",
        "Open", "Update", "Delete", "Name", "New", "From", "Until", "Today", "Small", "Medium", "Large", "Left", "Right",
        "Every", "minutes", "items", "sec", "found", "Checked at", "Looking…", "Look again", "Try again", "Check now",
        "Original", "Fit", "Size", "Show now", "Preview", "Previewing…", "Playing", "Automatic", "Always on",
        "Paused until 6 AM", "Dimming now", "Starts when macOS switches to Dark Mode", "Starts at",
        "Choose a video below", "Ramadan mode is on", "Ramadan mode is off", "No video chosen", "No folder chosen",
        "Connected · battery not reported yet", "No wireless devices found yet.", "No city found", "Sehri ends", "Iftar"}
PATTERNS = [r'L\("((?:[^"\\]|\\.)*)"\)', r'title:\s*"((?:[^"\\]|\\.)*)"', r'slider\("((?:[^"\\]|\\.)*)"',
            r'LabeledSlider\(title:\s*L\("((?:[^"\\]|\\.)*)"\)']

def keep(text):
    if text in SKIP or "\\(" in text or len(text) < 3 or len(text) > 72:
        return False
    if not re.search(r"[A-Za-z]", text):
        return False
    # Long explanations (footers) are not settings.
    if text.endswith(".") and len(text.split()) > 9:
        return False
    return True

entries = []
seen = set()
for rel in FILES:
    src = open(os.path.join(ROOT, rel), encoding="utf-8").read()
    starts = [(m.start(), m.group(2)) for m in re.finditer(r'^(private )?struct (\w+)', src, re.M)]
    for i, (start, name) in enumerate(starts):
        tab = TABS.get(name)
        if not tab:
            continue
        end = starts[i + 1][0] if i + 1 < len(starts) else len(src)
        body = src[start:end]
        for pattern in PATTERNS:
            for m in re.finditer(pattern, body):
                text = m.group(1)
                if keep(text) and (text, tab) not in seen:
                    seen.add((text, tab))
                    entries.append((text, tab))

out = ["// Generated by scripts/gen-settings-index.py: every label in Settings and its page.",
       "// Do not edit by hand; run the script after changing a Settings page.", "",
       "enum SettingsIndex {", "    static let labels: [(String, String)] = ["]
for text, tab in entries:
    out.append(f'        ("{text}", "{tab}"),')
out += ["    ]", "}", ""]
path = os.path.join(ROOT, "Sources/Uthon/App/SettingsIndex.swift")
new = "\n".join(out)
if not os.path.exists(path) or open(path, encoding="utf-8").read() != new:
    open(path, "w", encoding="utf-8").write(new)
print(f"Settings index: {len(entries)} labels")
